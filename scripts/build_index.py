#!/usr/bin/env python3
"""Write INDEX.md from the kit's own frontmatter. Stdlib only.

    python3 scripts/build_index.py          # rewrite INDEX.md
    python3 scripts/build_index.py --check  # exit 1 if INDEX.md is stale

The index is generated so it can't drift: check_kit.py runs --check.
Every command must sit in exactly one group below, or this exits 2.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "INDEX.md"

GROUPS = [
    ("Every day", ["test", "review", "debug", "commit", "pr", "security-review", "explain", "handoff"]),
    ("Before you build", ["brainstorm", "grill", "discovery", "design-brief", "sdd", "feature", "user-story", "bdd", "test-plan", "questionnaire"]),
    ("Decisions on record", ["adr", "rfc", "migration-plan", "rebuild"]),
    ("Tests and quality", ["coverage", "testgen", "playwright", "journey", "load-test", "entropy", "deslop", "design-pass", "rehearse", "lean"]),
    ("Security and supply chain", ["secrets-scan", "deps-audit", "supply-chain", "sbom", "threat-model", "pipeline-review", "soc2"]),
    ("Docs and operations", ["api-docs", "onboard", "runbook", "changelog", "bug", "retro"]),
    ("Adding your own", ["new-command", "new-skill", "new-agent"]),
]


def frontmatter(path):
    m = re.match(r"---\n(.*?)\n---\n", path.read_text(encoding="utf-8"), re.S)
    out = {}
    for line in (m.group(1) if m else "").splitlines():
        key, _, value = line.partition(":")
        out[key.strip()] = value.strip()
    return out


def docstring_line(path):
    m = re.search(r'"""(.+?)(?:\n|""")', path.read_text(encoding="utf-8"))
    return m.group(1).strip() if m else ""


def render():
    commands = {p.stem: frontmatter(p).get("description", "") for p in sorted((ROOT / "commands").glob("*.md"))}
    placed = [n for _, names in GROUPS for n in names]
    loose = sorted(set(commands) - set(placed))
    ghosts = sorted(set(placed) - set(commands))
    dupes = sorted({n for n in placed if placed.count(n) > 1})
    if loose or ghosts or dupes:
        sys.exit(f"build_index.py: GROUPS is out of date. not placed: {loose}; no such command: {ghosts}; twice: {dupes}")

    lines = [
        "# Index",
        "",
        "Generated by `scripts/build_index.py` from the kit's frontmatter. Edit the files, not this.",
        "",
        f"{len(commands)} commands, {len(list((ROOT / 'skills').glob('*/SKILL.md')))} skills, "
        f"{len(list((ROOT / 'agents').glob('*.md')))} helpers. Every command works with nothing typed after it.",
        "",
        "## Commands",
    ]
    for title, names in GROUPS:
        lines += ["", f"### {title}", "", "| Command | What it does |", "| --- | --- |"]
        lines += [f"| `/{n}` | {commands[n]} |" for n in names]
    lines += ["", "## Skills", "", "| Skill | Load it when |", "| --- | --- |"]
    for path in sorted((ROOT / "skills").glob("*/SKILL.md")):
        fm = frontmatter(path)
        lines.append(f"| `{fm.get('name', path.parent.name)}` | {fm.get('description', '')} |")
    lines += ["", "## Helpers", "", "| Helper | Job |", "| --- | --- |"]
    for path in sorted((ROOT / "agents").glob("*.md")):
        fm = frontmatter(path)
        lines.append(f"| `{fm.get('name', path.stem)}` | {fm.get('description', '')} |")
    lines += ["", "## Scripts", "", "| Script | What it does |", "| --- | --- |"]
    for path in sorted((ROOT / "scripts").glob("*.py")):
        lines.append(f"| `scripts/{path.name}` | {docstring_line(path)} |")
    return "\n".join(lines) + "\n"


def main(argv):
    text = render()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("INDEX.md is stale: run python3 scripts/build_index.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
